#!/usr/bin/env bash
# Validate committed website bytes in isolation before updating a public checkout.
set -euo pipefail
export PYTHONDONTWRITEBYTECODE=1
fail() { echo "website-export: FAIL: $1" >&2; exit 1; }
[ "$#" -eq 1 ] || fail 'usage: scripts/export-public.sh <dest>'
[ -n "${OPENPLANS_DENYLIST_FILE:-}" ] || fail 'OPENPLANS_DENYLIST_FILE is required'
[ -r "$OPENPLANS_DENYLIST_FILE" ] || fail 'cannot read publication denylist'
# Preserve relative caller-supplied policy paths when the gate changes directories.
OPENPLANS_DENYLIST_FILE=$(python3 -c 'import pathlib,sys; print(pathlib.Path(sys.argv[1]).resolve())' "$OPENPLANS_DENYLIST_FILE")
export OPENPLANS_DENYLIST_FILE
for command in git python3 rsync tar; do
  command -v "$command" >/dev/null || fail "missing $command"
done
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
REPO=$(git -C "$ROOT" rev-parse --show-toplevel) || fail 'source must be a Git checkout'
PREFIX=$(git -C "$ROOT" rev-parse --show-prefix)
COMMIT=$(git -C "$REPO" rev-parse --verify 'HEAD^{commit}')
[ -z "$(git -C "$ROOT" status --porcelain --untracked-files=all -- .)" ] || fail 'source website tree is dirty; commit changes first'
DEST=$(python3 - "$REPO" "$1" <<'PY'
import sys
from pathlib import Path
source = Path(sys.argv[1]).resolve()
raw = Path(sys.argv[2]).absolute()
if raw.is_symlink():
    sys.exit('website-export: FAIL: destination must not be a symlink')
dest = raw.resolve()
if dest == source or source in dest.parents or dest in source.parents:
    sys.exit('website-export: FAIL: destination must be outside and not contain the source checkout')
if dest.exists() and not dest.is_dir():
    sys.exit('website-export: FAIL: destination must be a directory')
print(dest)
PY
)
TMP=$(mktemp -d "${TMPDIR:-/tmp}/website-export.XXXXXX")
trap 'rm -rf "$TMP"' EXIT
mkdir "$TMP/tree"
TREE=${COMMIT}${PREFIX:+:${PREFIX%/}}
git -C "$REPO" archive "$TREE" | tar -xf - -C "$TMP/tree"
# The archive has no Git metadata: history checks use the committed source only
# in the incubator; all content and negative-control checks also run standalone.
python3 "$TMP/tree/tools/check-neutral.py" "$TMP/tree"
cp -R "$TMP/tree" "$TMP/check"
"$TMP/check/tools/gate.sh" --full > "$TMP/gate.log" 2>&1 || { cat "$TMP/gate.log"; fail 'isolated full gate'; }
cat "$TMP/gate.log"
[ "$(tail -n 1 "$TMP/gate.log")" = PASS ] || fail 'isolated gate did not print PASS'
# Sync the untouched archive, never output generated by the validation copy.
mkdir -p "$DEST"
rsync -a --delete --exclude='/.git' --exclude='/.vercel' --exclude='/.lanes' --exclude='/.env*' "$TMP/tree/" "$DEST/"
python3 "$TMP/tree/tools/check-neutral.py" "$DEST"
printf 'website-export: PASS\n'
